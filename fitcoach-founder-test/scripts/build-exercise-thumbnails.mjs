#!/usr/bin/env node

import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const APP_ROOT = path.resolve(SCRIPT_DIR, "..");
const SOURCE_DIR = path.join(APP_ROOT, "v040/assets/exercises/generated");
const OUTPUT_DIR = path.join(SOURCE_DIR, "thumbs");
const DEFINITIONS_PATH = path.join(APP_ROOT, "v040/data/generated-thumbnail-definitions.mjs");
const CWEBP = process.env.CWEBP_BIN || "cwebp";
const WIDTH = 480;
const QUALITY = 78;

function sha256(buffer) {
  return createHash("sha256").update(buffer).digest("hex");
}

function encode(input, output) {
  const result = spawnSync(CWEBP, [
    "-quiet",
    "-mt",
    "-m", "6",
    "-q", String(QUALITY),
    "-metadata", "none",
    "-resize", String(WIDTH), "0",
    input,
    "-o", output,
  ], { stdio: "pipe" });
  if (result.error?.code === "ENOENT") {
    throw new Error(`cwebp was not found. Install libwebp or set CWEBP_BIN. (${result.error.message})`);
  }
  if (result.status !== 0) {
    throw new Error(`cwebp failed for ${path.basename(input)}: ${String(result.stderr || "unknown error").trim()}`);
  }
}

await mkdir(OUTPUT_DIR, { recursive: true });
const sourceFiles = (await readdir(SOURCE_DIR, { withFileTypes: true }))
  .filter(entry => entry.isFile() && /-premium-v\d+\.png$/u.test(entry.name))
  .map(entry => entry.name)
  .sort((a, b) => a.localeCompare(b));

if (sourceFiles.length !== 100) {
  throw new Error(`Expected 100 production poster PNGs, found ${sourceFiles.length}. Refusing a partial release.`);
}

const definitions = [];
let sourceBytes = 0;
let thumbnailBytes = 0;
for (const sourceName of sourceFiles) {
  const sourcePath = path.join(SOURCE_DIR, sourceName);
  const outputName = sourceName.replace(/\.png$/u, ".webp");
  const outputPath = path.join(OUTPUT_DIR, outputName);
  encode(sourcePath, outputPath);
  const [sourceInfo, outputInfo, outputBuffer] = await Promise.all([
    stat(sourcePath),
    stat(outputPath),
    readFile(outputPath),
  ]);
  if (outputInfo.size >= sourceInfo.size) {
    throw new Error(`Thumbnail ${outputName} is not smaller than its source.`);
  }
  sourceBytes += sourceInfo.size;
  thumbnailBytes += outputInfo.size;
  definitions.push({
    sourceFile: `generated/${sourceName}`,
    file: `generated/thumbs/${outputName}`,
    width: WIDTH,
    height: WIDTH,
    format: "webp",
    bytes: outputInfo.size,
    sha256: sha256(outputBuffer),
  });
}

const moduleSource = `/**\n * Generated by scripts/build-exercise-thumbnails.mjs.\n * Do not hand-edit. Rebuild after changing production poster sources.\n */\nexport const GENERATED_THUMBNAIL_DEFINITIONS = Object.freeze(${JSON.stringify(definitions, null, 2)}.map(item => Object.freeze(item)));\n\nconst BY_SOURCE = new Map(GENERATED_THUMBNAIL_DEFINITIONS.map(item => [item.sourceFile, item]));\nexport function getGeneratedThumbnail(sourceFile) {\n  return BY_SOURCE.get(sourceFile) || null;\n}\n`;
await writeFile(DEFINITIONS_PATH, moduleSource, "utf8");

const reduction = Math.round((1 - thumbnailBytes / sourceBytes) * 1_000) / 10;
process.stdout.write(`Built ${definitions.length} WebP thumbnails: ${(sourceBytes / 1024 / 1024).toFixed(1)} MiB -> ${(thumbnailBytes / 1024 / 1024).toFixed(1)} MiB (${reduction}% smaller).\n`);
